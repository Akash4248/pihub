from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass
class ParsedSection:
    title: str
    content: str


class SectionParser:
    """Parse educational text into chapter/section-level blocks.

    Supports structure-aware Markdown AST headings (#, ##, ###) generated by
    Docling or PyMuPDF4LLM, with robust fallback for plain-text documents.
    Math equations, expressions, and colon-terminated prose are explicitly
    prevented from being falsely detected as section headings.
    """

    HEADING_PATTERNS = [
        re.compile(r"^(?:chapter|unit|lesson|section)\s+\d+[:\s.-]*.*", re.IGNORECASE),
        re.compile(r"^\d+(\.\d+)+\s+\S+.*"),
        re.compile(r"^(?:ಅಧ್ಯಾಯ|ಪಾಠ|ಘಟಕ)\s+\d+[:\s.-]*.*"),
    ]

    NON_HEADING_COLONS = (
        "as follows:", "such that:", "for example:", "e.g.:", "note:",
        "namely:", "defined as:", "that is:", "i.e.:", "where:", "since:",
    )

    MATH_OPERATOR_CHARS = set("=≅∠∆π≤≥<>≈+-*/÷×")

    def parse(self, text: str) -> list[ParsedSection]:
        lines = [line.rstrip() for line in text.splitlines()]
        sections: list[ParsedSection] = []
        current_title = "Introduction"
        current_lines: list[str] = []

        has_markdown_headings = bool(re.search(r"^\s*#{1,6}\s+\S+", text, re.MULTILINE))

        def flush() -> None:
            nonlocal current_lines
            content = "\n".join(current_lines).strip()
            if content:
                sections.append(ParsedSection(title=current_title, content=content))
            current_lines = []

        for line in lines:
            stripped = line.strip()
            if not stripped:
                current_lines.append("")
                continue

            if self._is_heading(stripped, markdown_mode=has_markdown_headings):
                if current_lines:
                    flush()
                current_title = self._clean_title(stripped)
            else:
                current_lines.append(stripped)

        if current_lines:
            flush()

        if not sections:
            sections.append(ParsedSection(title="Document", content=text.strip()))
        return sections

    def _clean_title(self, raw_title: str) -> str:
        # Strip Markdown heading hashes and formatting
        cleaned = re.sub(r"^\s*#{1,6}\s*", "", raw_title).strip()
        cleaned = re.sub(r"\*\*([^*]+)\*\*", r"\1", cleaned)
        cleaned = re.sub(r"__([^_]+)__", r"\1", cleaned)
        cleaned = re.sub(r"\*([^*]+)\*", r"\1", cleaned)
        cleaned = re.sub(r"_([^_]+)_", r"\1", cleaned)
        return cleaned.strip(" *_-#:")

    def _is_heading(self, line: str, markdown_mode: bool = False) -> bool:
        # In Markdown mode, trust structural header hashes
        if line.startswith("#"):
            return bool(re.match(r"^#{1,6}\s+\S+", line))

        # If the document has Markdown headings elsewhere, do NOT invent headings
        # from unhashed lines (prevents equations and prose from polluting section tree)
        if markdown_mode:
            return False

        # Disqualify any line containing mathematical operator symbols
        if any(char in self.MATH_OPERATOR_CHARS for char in line):
            return False

        lowered = line.lower()
        if any(lowered.endswith(suffix) for suffix in self.NON_HEADING_COLONS):
            return False

        # Explicit numbered or labeled chapter/section headings
        if any(pattern.match(line) for pattern in self.HEADING_PATTERNS):
            return True

        words = line.split()
        if len(words) < 2 or len(words) > 12:
            return False

        if line.endswith(":") and len(words) <= 8 and line[0].isupper():
            # Ensure it is not a common sentence fragment
            if not any(token in ("the", "is", "are", "we", "can", "in", "let") for token in words[:2]):
                return True

        if line.isupper() and 2 <= len(words) <= 8:
            # Must contain actual letters, not just symbols or numbers
            letters = [c for c in line if c.isalpha()]
            if len(letters) >= 6:
                return True

        return False
